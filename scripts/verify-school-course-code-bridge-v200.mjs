import fs from 'node:fs';
const files=fs.readdirSync('supabase/migrations').filter(x=>x.endsWith('_school_course_code_bridge_v200.sql'));
if(files.length!==1)throw new Error(`Expected one Wave 2A migration, found ${files.length}`);
const sql=fs.readFileSync('supabase/migrations/'+files[0],'utf8');
const need=(x,m)=>{if(!sql.includes(x))throw new Error(m)};
const forbid=(re,m)=>{if(re.test(sql))throw new Error(m)};
need('alter table public.school_lessons add column course_code text','lesson course bridge missing');
need('alter table public.school_progress add column course_code text','progress course bridge missing');
need("set course_code=e.course_code","exam-backed progress mapping missing");
need("p.lesson_code like 'course:%'","course summary mapping missing");
need('private.nh7_school_progress_course_code_guard_v200','old-client course guard missing');
need("set search_path=''","private trigger search_path must be pinned empty");
need('school_lessons_course_code_fkey_v200','lesson course FK missing');
need('school_progress_course_code_fkey_v200','progress course FK missing');
forbid(/create\s+table\s+.*school_course_(?:stages|stage_lessons|prerequisites|access_grants)/is,'Wave 2A must not create stage/prerequisite/grant tables');
forbid(/alter\s+table\s+public\.school_courses\s+add\s+column/is,'Wave 2A must not expand Course Studio metadata');
forbid(/\bdelete\s+from\b/i,'Wave 2A must not delete School history');
console.log(`School Course Code Bridge v200 verifier: PASS (${files[0]})`);
console.log('Scope: lessons + progress course ownership only; stages/grants/Course Studio untouched');
